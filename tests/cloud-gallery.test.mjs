import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {randomUUID} from 'node:crypto';
import {DatabaseSync} from 'node:sqlite';
import {database,chunkSize,putChunk,putVersion,catalogue,imageResponse,createLink,sharedItems} from '../lib/gallery/store.mjs';
const dir=mkdtempSync(join(tmpdir(),'lume-gallery-test-'));
test('volumes persistem versões imutáveis e a lista de partes só pode apontar para dados da própria conta', async()=>{
  const db=database(dir), photo=Buffer.alloc(chunkSize+25,31);
  Buffer.from([137,80,78,71,13,10,26,10]).copy(photo);
  const parts=[putChunk(db,'a',photo.subarray(0,chunkSize)),putChunk(db,'a',photo.subarray(chunkSize))];
  const image={type:'image/png',parts}, id=randomUUID();
  const meta={id,root:id,title:'Exemplo',prompt:'',size:'1024x1024',quality:'medium',created:1};
  const input={meta,image,thumb:image};
  assert.throws(()=>putVersion(db,'b',input),/incompleto/);
  putVersion(db,'a',input);putVersion(db,'a',input);
  assert.throws(()=>putVersion(db,'a',{...input,meta:{...meta,title:'Outra'}}),/identificador/);
  assert.equal(catalogue(db,'a').length,1);assert.equal(catalogue(db,'b').length,0);
  assert.equal(imageResponse(db,'b',id).status,404);
  const second=new DatabaseSync(join(dir,'gallery.sqlite'));
  assert.deepEqual(Buffer.from(await imageResponse(second,'a',id).arrayBuffer()),photo);second.close();
  const child=randomUUID(),br=randomUUID();
  putVersion(db,'a',{...input,meta:{...meta,id:child,parent:id,created:2}});
  putVersion(db,'a',{...input,meta:{...meta,id:br,parent:id,created:3}});
  assert.throws(()=>putVersion(db,'a',{...input,meta:{...meta,id:randomUUID(),parent:randomUUID()}}),/anterior/);
  const single=createLink(db,'a','photo',child),project=createLink(db,'a','project',id);
  assert.equal(createLink(db,'a','photo',child),single);
  assert.deepEqual(sharedItems(db,single).items.map(i=>i.id),[child]);
  assert.deepEqual(sharedItems(db,project).items.map(i=>i.id),[br,child,id]);
  assert.throws(()=>createLink(db,'b','project',id),/Sincronize/);
  db.prepare('DELETE FROM links WHERE owner=? AND token=?').run('b',single);assert.ok(sharedItems(db,single));
  db.prepare('DELETE FROM links WHERE owner=? AND token=?').run('a',single);assert.equal(sharedItems(db,single),null);
  assert.ok(sharedItems(db,project));db.close();rmSync(dir,{recursive:true,force:true});
});
